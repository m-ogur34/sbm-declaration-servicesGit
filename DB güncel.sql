-- =============================================
-- 1. SEQUENCES
-- =============================================
CREATE SEQUENCE CUSTOMER.ALZ_SBM_MUNICIPALITY_SEQ START WITH 1 MAXVALUE 999999999999999999999999999 MINVALUE 1 INCREMENT BY 1 NOCYCLE CACHE 20 NOORDER;
CREATE SEQUENCE CUSTOMER.ALZ_SBM_DECL_PROCESS_SEQ START WITH 1 MAXVALUE 999999999999999999999999999 MINVALUE 1 INCREMENT BY 1 NOCYCLE CACHE 20 NOORDER;
CREATE SEQUENCE CUSTOMER.ALZ_SBM_DECL_LOG_SEQ START WITH 1 MAXVALUE 999999999999999999999999999 MINVALUE 1 INCREMENT BY 1 NOCYCLE CACHE 20 NOORDER;

CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_MUNICIPALITY_SEQ FOR CUSTOMER.ALZ_SBM_MUNICIPALITY_SEQ;
CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_DECL_PROCESS_SEQ FOR CUSTOMER.ALZ_SBM_DECL_PROCESS_SEQ;
CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_DECL_LOG_SEQ     FOR CUSTOMER.ALZ_SBM_DECL_LOG_SEQ;

-- =============================================
-- 2. TABLES
-- =============================================

-- 2.1 Belediye Referans Tablosu
CREATE TABLE CUSTOMER.ALZ_SBM_MUNICIPALITY (
    ID                  NUMBER(10)     DEFAULT CUSTOMER.ALZ_SBM_MUNICIPALITY_SEQ.NEXTVAL,
    CITY_CODE           NUMBER(3)      NOT NULL,
    DISTRICT_CODE       NUMBER(10)     NOT NULL,
    MUNICIPALITY_NAME   VARCHAR2(255)  NOT NULL,
    KEP_EMAIL           VARCHAR2(320),
    EMAIL               VARCHAR2(320),
    PHONE               VARCHAR2(30),
    POSTAL_ADDRESS      VARCHAR2(1000),
    NOTIFICATION_TYPE   VARCHAR2(20)   DEFAULT 'BOTH',
    CONTACT_PERSON      VARCHAR2(255),
    IS_ACTIVE           CHAR(1)        DEFAULT 'Y' NOT NULL
);

-- 2.2 Beyanname Süreç Tablosu
CREATE TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS (
    ID                          NUMBER(10)      DEFAULT CUSTOMER.ALZ_SBM_DECL_PROCESS_SEQ.NEXTVAL,
    DECLARATION_MONTH           NUMBER(2),       -- SBM: ay
    CITY_CODE                   NUMBER(3),       -- SBM: ilKodu
    DISTRICT_CODE               NUMBER(10),      -- SBM: ilceKodu
    COMPANY_CODE                VARCHAR2(3),     -- SBM: sigortaSirketKodu
    PAYMENT_DATE                DATE,            -- SBM: sonOdemeTarihi
    DECLARATION_YEAR            NUMBER(4),       -- SBM: yil
    SBM_FILE_NO                 VARCHAR2(100),   -- SBM: ysvDosyaNo
    RECEIVED_PREMIUM_AMOUNT     NUMBER(15,2),    -- SBM: alinanPrimTutari
    CANCELLED_PREMIUM_AMOUNT    NUMBER(15,2),    -- SBM: iptalPrimTutari
    PREV_MONTH_REFUND_AMOUNT    NUMBER(15,2),    -- SBM: gecmisAyIadeTutari
    MOVABLE_TYPE                VARCHAR2(20),    -- SBM: menkulTipi ("MENKUL"/"GAYRIMENKUL")
    TAX_AMOUNT                  NUMBER(15,2),    -- SBM: odenecekVergi
    TAX_RATIO                   NUMBER(3),       -- SBM: vergiOrani
    TAX_PREMIUM_AMOUNT          NUMBER(15,2),    -- SBM: vergiPrimTutari
    STATUS                      VARCHAR2(20),    -- Dahili: NEW/PROCESSING/SENT/ERROR/COMPLETED
    DATE_CREATED                DATE            DEFAULT SYSDATE,
    CREATED_BY_USER             VARCHAR2(100),
    DATE_UPDATED                DATE,
    UPDATED_BY_USER             VARCHAR2(100),
    DATE_SENT                   DATE,
    SENT_BY_USER                VARCHAR2(100),
    ERROR_DETAILS               VARCHAR2(2000),
    SOURCE_FILE_NAME            VARCHAR2(500)
);

-- 2.3 REST API Log Tablosu (yasal kanıt)
CREATE TABLE CUSTOMER.ALZ_SBM_DECL_LOG (
    ID                  NUMBER(10)      DEFAULT CUSTOMER.ALZ_SBM_DECL_LOG_SEQ.NEXTVAL,
    PROCESS_ID          NUMBER(10),
    OPERATION_TYPE      VARCHAR2(30),
    LOG_LEVEL           VARCHAR2(50),
    LOG_MESSAGE         CLOB,
    REQUEST_PAYLOAD     CLOB,
    RESPONSE_PAYLOAD    CLOB,
    DATE_CREATED        DATE            DEFAULT SYSDATE
);

-- =============================================
-- 3. CONSTRAINTS
-- =============================================
ALTER TABLE CUSTOMER.ALZ_SBM_MUNICIPALITY  ADD CONSTRAINT PK_ALZ_SBM_MUNICIPALITY  PRIMARY KEY (ID);
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS  ADD CONSTRAINT PK_ALZ_SBM_DECL_PROCESS  PRIMARY KEY (ID);
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_LOG      ADD CONSTRAINT PK_ALZ_SBM_DECL_LOG      PRIMARY KEY (ID);
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_LOG ADD CONSTRAINT FK_SBM_LOG_PROCESS FOREIGN KEY (PROCESS_ID) REFERENCES CUSTOMER.ALZ_SBM_DECL_PROCESS(ID);
ALTER TABLE CUSTOMER.ALZ_SBM_MUNICIPALITY ADD CONSTRAINT UQ_MUNICIPALITY_CITY_DIST UNIQUE (CITY_CODE, DISTRICT_CODE);
ALTER TABLE CUSTOMER.ALZ_SBM_MUNICIPALITY ADD CONSTRAINT CHK_MUNICIPALITY_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'));
ALTER TABLE CUSTOMER.ALZ_SBM_MUNICIPALITY ADD CONSTRAINT CHK_MUNICIPALITY_NOTIF_TYPE CHECK (NOTIFICATION_TYPE IN ('KEP', 'POSTAL', 'BOTH', 'NONE'));
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS ADD CONSTRAINT CHK_DECL_MOVABLE_TYPE CHECK (MOVABLE_TYPE IN ('MENKUL', 'GAYRIMENKUL'));
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS ADD CONSTRAINT CHK_DECL_STATUS CHECK (STATUS IN ('NEW', 'PROCESSING', 'SENT', 'ERROR', 'COMPLETED'));
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS ADD CONSTRAINT CHK_DECL_MONTH CHECK (DECLARATION_MONTH BETWEEN 1 AND 12);
ALTER TABLE CUSTOMER.ALZ_SBM_DECL_PROCESS ADD CONSTRAINT CHK_DECL_YEAR CHECK (DECLARATION_YEAR BETWEEN 2000 AND 2099);

-- =============================================
-- 4. INDEXES
-- =============================================
CREATE INDEX CUSTOMER.IDX_DECL_PROC_STATUS ON CUSTOMER.ALZ_SBM_DECL_PROCESS(STATUS);
CREATE INDEX CUSTOMER.IDX_DECL_PROC_FILE_NO ON CUSTOMER.ALZ_SBM_DECL_PROCESS(SBM_FILE_NO);
CREATE INDEX CUSTOMER.IDX_DECL_PROC_CITY_DIST ON CUSTOMER.ALZ_SBM_DECL_PROCESS(CITY_CODE, DISTRICT_CODE);
CREATE INDEX CUSTOMER.IDX_DECL_PROC_DATE_CREATED ON CUSTOMER.ALZ_SBM_DECL_PROCESS(DATE_CREATED);
CREATE INDEX CUSTOMER.IDX_DECL_PROC_YEAR_MONTH ON CUSTOMER.ALZ_SBM_DECL_PROCESS(DECLARATION_YEAR, DECLARATION_MONTH);
CREATE INDEX CUSTOMER.IDX_DECL_LOG_PROCESS_ID ON CUSTOMER.ALZ_SBM_DECL_LOG(PROCESS_ID);
CREATE INDEX CUSTOMER.IDX_DECL_LOG_DATE ON CUSTOMER.ALZ_SBM_DECL_LOG(DATE_CREATED);
CREATE INDEX CUSTOMER.IDX_MUNICIPALITY_CITY ON CUSTOMER.ALZ_SBM_MUNICIPALITY(CITY_CODE);

-- =============================================
-- 5. SYNONYMS
-- =============================================
CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_MUNICIPALITY FOR CUSTOMER.ALZ_SBM_MUNICIPALITY;
CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_DECL_PROCESS FOR CUSTOMER.ALZ_SBM_DECL_PROCESS;
CREATE OR REPLACE PUBLIC SYNONYM ALZ_SBM_DECL_LOG     FOR CUSTOMER.ALZ_SBM_DECL_LOG;

