GRANT SELECT ON CUSTOMER.ALZ_SBM_DECL_LOG_SEQ     TO DEVELOPER_USER, DEVELOPER_USER_GORME, READ_ROLE, ALLZWEBPOL;
GRANT DELETE, INSERT, SELECT, UPDATE ON CUSTOMER.ALZ_SBM_MUNICIPALITY TO DEVELOPER_USER, DEVELOPER_USER_GORME, ALLZWEBPOL;
